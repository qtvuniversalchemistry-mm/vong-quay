/* =========================================================
   Công cụ: Xóa nhãn AI & thông tin ẩn trong ảnh
   Xóa metadata (C2PA / Content Credentials, XMP, IPTC, EXIF, GPS, chú thích, tham số AI)
   trực tiếp trong file, KHÔNG nén lại ảnh → giữ nguyên 100% chất lượng điểm ảnh.
   Hỗ trợ không mất chất lượng: JPG, PNG, WebP. Định dạng khác được chuyển sang JPG/PNG.
   ========================================================= */
(function () {
  "use strict";
  var M = window.MAINN, F = M.files;
  var MAX_FILES = 200;
  var AI_RE = /trainedAlgorithmicMedia|compositeSynthetic|c2pa|contentauth|openai|chatgpt|dall[\s·-]?e|midjourney|firefly|gemini|imagen|google ai|stable[\s_-]?diffusion|comfyui|automatic1111|novelai|ideogram|leonardo\.ai|runway|flux|sdxl|negative prompt|made with ai|ai generated|generated by ai/i;
  var LABELS = {
    c2pa: "Content Credentials (C2PA)",
    ai: "Dấu hiệu tạo bằng AI",
    aiParams: "Câu lệnh / tham số AI",
    exif: "EXIF (thông tin máy, phần mềm)",
    gps: "Vị trí GPS",
    xmp: "XMP",
    iptc: "IPTC",
    comment: "Chú thích ẩn",
    text: "Văn bản ẩn",
    extra: "Ảnh phụ / dữ liệu thừa"
  };
  var DL_ICON = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4M7 10l5 5 5-5M12 15V3"/></svg>';
  var X_ICON = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><path d="M18 6 6 18M6 6l12 12"/></svg>';

  function latin1(u8) {
    var s = "", step = 8192;
    for (var i = 0; i < u8.length; i += step) s += String.fromCharCode.apply(null, u8.subarray(i, Math.min(u8.length, i + step)));
    return s;
  }
  function ascii(u8, off, n) { return String.fromCharCode.apply(null, u8.subarray(off, off + n)); }
  function concat(parts) {
    var n = 0; parts.forEach(function (p) { n += p.length; });
    var out = new Uint8Array(n), o = 0;
    parts.forEach(function (p) { out.set(p, o); o += p.length; });
    return out;
  }
  function flagAI(text, found) { if (AI_RE.test(text)) found.ai = true; }

  /* ---------- JPEG ---------- */
  // Đọc EXIF: hướng xoay + có GPS hay không
  function readExif(seg, found) {
    var t = 10; // sau "FFE1 len Exif\0\0"
    if (seg.length < t + 8) return 1;
    var v = new DataView(seg.buffer, seg.byteOffset, seg.length);
    var little = v.getUint16(t) === 0x4949, orient = 1;
    try {
      var ifd = t + v.getUint32(t + 4, little), n = v.getUint16(ifd, little);
      for (var i = 0; i < n; i++) {
        var e = ifd + 2 + i * 12, tag = v.getUint16(e, little);
        if (tag === 0x0112) orient = v.getUint16(e + 8, little);
        if (tag === 0x8825) found.gps = true;
      }
    } catch (err) {}
    return orient;
  }
  // Tạo khối EXIF tối thiểu chỉ chứa hướng xoay, để ảnh không bị xoay sai sau khi xóa EXIF
  function orientationSegment(o) {
    return new Uint8Array([
      0xff, 0xe1, 0x00, 0x22, 0x45, 0x78, 0x69, 0x66, 0x00, 0x00,       // APP1, len 34, "Exif\0\0"
      0x4d, 0x4d, 0x00, 0x2a, 0x00, 0x00, 0x00, 0x08,                   // TIFF big-endian, IFD0 @8
      0x00, 0x01,                                                       // 1 mục
      0x01, 0x12, 0x00, 0x03, 0x00, 0x00, 0x00, 0x01, 0x00, o, 0x00, 0x00, // Orientation
      0x00, 0x00, 0x00, 0x00                                            // hết IFD
    ]);
  }

  function stripJpeg(u8, found) {
    var parts = [u8.subarray(0, 2)], off = 2, orient = 1, app0End = 1, len = u8.length;
    while (off + 4 <= len) {
      if (u8[off] !== 0xff) throw new Error("jpeg");
      var m = u8[off + 1];
      if (m === 0xff) { off++; continue; }
      if (m === 0xd9) { parts.push(u8.subarray(off, off + 2)); off += 2; break; }
      if ((m >= 0xd0 && m <= 0xd7) || m === 0x01) { parts.push(u8.subarray(off, off + 2)); off += 2; continue; }
      var segLen = (u8[off + 2] << 8) | u8[off + 3], end = off + 2 + segLen;
      if (end > len) throw new Error("jpeg");
      var seg = u8.subarray(off, end);
      if (m === 0xda) {
        // Dữ liệu ảnh: chép nguyên vẹn đến điểm kết thúc ảnh (FFD9)
        var i = end;
        while (i < len - 1 && !(u8[i] === 0xff && u8[i + 1] === 0xd9)) i++;
        var stop = Math.min(len, i + 2);
        parts.push(u8.subarray(off, stop));
        off = stop;
        break;
      }
      var keep = true, head = ascii(seg, 4, Math.min(30, seg.length - 4));
      if (m === 0xe0) keep = /^JF(IF|XX)/.test(head);
      else if (m === 0xe1) {
        keep = false;
        if (/^Exif/.test(head)) { found.exif = true; orient = readExif(seg, found); flagAI(latin1(seg), found); }
        else { found.xmp = true; flagAI(latin1(seg), found); }
      } else if (m === 0xe2) {
        keep = /^ICC_PROFILE/.test(head);
        if (!keep) found.extra = true;
      } else if (m === 0xeb) { keep = false; found.c2pa = true; found.ai = found.ai || AI_RE.test(latin1(seg)); }
      else if (m === 0xed) { keep = false; found.iptc = true; flagAI(latin1(seg), found); }
      else if (m === 0xee) keep = true; // Adobe: cần cho màu chính xác
      else if (m >= 0xe3 && m <= 0xef) { keep = false; found.extra = true; flagAI(latin1(seg), found); }
      else if (m === 0xfe) { keep = false; found.comment = true; flagAI(latin1(seg), found); }
      if (keep) { parts.push(seg); if (m === 0xe0) app0End = parts.length; }
      off = end;
    }
    if (off < len) found.extra = true; // dữ liệu thừa sau ảnh (ảnh phụ, motion photo…)
    if (orient > 1 && orient <= 8) parts.splice(app0End, 0, orientationSegment(orient));
    return concat(parts);
  }

  /* ---------- PNG ---------- */
  var PNG_KEEP = { tRNS: 1, gAMA: 1, cHRM: 1, sRGB: 1, iCCP: 1, sBIT: 1, pHYs: 1, bKGD: 1, acTL: 1, fcTL: 1, fdAT: 1, cICP: 1, mDCV: 1, cLLI: 1, mDCv: 1, cLLi: 1 };
  function stripPng(u8, found) {
    var parts = [u8.subarray(0, 8)], off = 8, len = u8.length;
    var v = new DataView(u8.buffer, u8.byteOffset, u8.length);
    while (off + 12 <= len) {
      var n = v.getUint32(off), type = ascii(u8, off + 4, 4), end = off + 12 + n;
      if (end > len) throw new Error("png");
      var critical = type.charCodeAt(0) < 97;
      if (critical || PNG_KEEP[type]) parts.push(u8.subarray(off, end));
      else {
        var data = latin1(u8.subarray(off + 8, off + 8 + n));
        if (type === "eXIf") { found.exif = true; flagAI(data, found); }
        else if (type === "caBX") { found.c2pa = true; found.ai = true; }
        else if (/^(tEXt|zTXt|iTXt)$/.test(type)) {
          var key = data.split("\0")[0];
          if (/^XML:com\.adobe\.xmp$/.test(key)) found.xmp = true;
          else if (/^(parameters|prompt|workflow|Dream|sd-metadata|invokeai)/i.test(key)) { found.aiParams = true; found.ai = true; }
          else found.text = true;
          flagAI(data, found);
        } else found.extra = true;
      }
      off = end;
      if (type === "IEND") break;
    }
    if (off < len) found.extra = true;
    return concat(parts);
  }

  /* ---------- WebP ---------- */
  var WEBP_KEEP = { "VP8 ": 1, VP8L: 1, VP8X: 1, ALPH: 1, ANIM: 1, ANMF: 1, ICCP: 1 };
  function stripWebp(u8, found) {
    var v = new DataView(u8.buffer, u8.byteOffset, u8.length), parts = [], off = 12, len = Math.min(u8.length, v.getUint32(4, true) + 8);
    while (off + 8 <= len) {
      var id = ascii(u8, off, 4), n = v.getUint32(off + 4, true), end = off + 8 + n + (n & 1);
      if (off + 8 + n > len) throw new Error("webp");
      var chunk = u8.subarray(off, Math.min(end, len));
      if (WEBP_KEEP[id]) {
        if (id === "VP8X") { chunk = chunk.slice(); chunk[8] &= ~(0x08 | 0x04); } // bỏ cờ EXIF, XMP
        parts.push(chunk);
      } else {
        var data = latin1(u8.subarray(off + 8, off + 8 + n));
        if (id === "EXIF") found.exif = true;
        else if (id === "XMP ") found.xmp = true;
        else if (id === "C2PA") { found.c2pa = true; found.ai = true; }
        else found.extra = true;
        flagAI(data, found);
      }
      off = end;
    }
    if (u8.length > len) found.extra = true;
    var body = concat(parts), head = new Uint8Array(12);
    head.set(u8.subarray(0, 12));
    new DataView(head.buffer).setUint32(4, body.length + 4, true);
    return concat([head, body]);
  }

  /* ---------- Định dạng khác: vẽ lại ảnh (mất toàn bộ thông tin ẩn) ---------- */
  function reencode(file, found) {
    return F.loadImage(file).then(function (img) {
      var keepAlpha = /gif|png|bmp|webp/i.test(file.type);
      var type = keepAlpha ? "image/png" : "image/jpeg";
      var c = F.drawToCanvas(img, 0, !keepAlpha);
      if (img.close) img.close();
      found.extra = true;
      return F.canvasToBlob(c, type, 0.95).then(function (b) {
        return { blob: b, name: F.withExt(file.name, keepAlpha ? "png" : "jpg"), converted: true };
      });
    });
  }

  function detectType(u8) {
    if (u8[0] === 0xff && u8[1] === 0xd8) return "jpeg";
    if (u8[0] === 0x89 && ascii(u8, 1, 3) === "PNG") return "png";
    if (ascii(u8, 0, 4) === "RIFF" && ascii(u8, 8, 4) === "WEBP") return "webp";
    return null;
  }

  function processFile(file) {
    var found = {};
    return file.arrayBuffer().then(function (buf) {
      var u8 = new Uint8Array(buf), kind = detectType(u8), out;
      if (!kind) return reencode(file, found).then(function (r) { r.found = found; return r; });
      try {
        out = kind === "jpeg" ? stripJpeg(u8, found) : kind === "png" ? stripPng(u8, found) : stripWebp(u8, found);
      } catch (e) {
        return reencode(file, found).then(function (r) { r.found = found; return r; });
      }
      var mime = { jpeg: "image/jpeg", png: "image/png", webp: "image/webp" }[kind];
      return { blob: new Blob([out], { type: mime }), name: file.name, found: found, converted: false };
    });
  }

  /* ---------- Giao diện ---------- */
  var $ = function (id) { return document.getElementById(id); };
  var el = {
    list: $("fileList"), listHead: $("listHead"), listTitle: $("listTitle"), clearAll: $("btnClearAll"),
    zip: $("btnZip"), zipText: $("btnZipText"), stats: $("stats")
  };
  var items = [], uid = 0, running = false;

  function badges(found) {
    var keys = Object.keys(LABELS).filter(function (k) { return found[k]; });
    if (!keys.length) return '<span class="tag tag--ok">Không có thông tin ẩn</span>';
    return keys.map(function (k) {
      return '<span class="tag' + (k === "ai" || k === "c2pa" || k === "aiParams" ? " tag--ai" : k === "gps" ? " tag--warn" : "") + '">' + LABELS[k] + "</span>";
    }).join("");
  }

  function rowHtml(it) {
    var meta, r = it.result;
    if (it.status === "pending" || it.status === "working") meta = '<span><span class="spinner"></span> Đang kiểm tra…</span>';
    else if (it.status === "error") meta = '<span class="status-err">Không đọc được ảnh này.</span>';
    else {
      meta = "<span>" + F.formatBytes(it.file.size) + " → <strong>" + F.formatBytes(r.blob.size) + "</strong></span>" +
        (r.converted ? "<span>Đã chuyển sang " + r.name.split(".").pop().toUpperCase() + "</span>" : "<span>Giữ nguyên chất lượng ảnh</span>") +
        '<div class="tags">' + (Object.keys(r.found).length ? '<span class="tags__label">Đã xóa:</span>' : "") + badges(r.found) + "</div>";
    }
    return '<img class="file-row__thumb" src="' + it.thumb + '" alt="">' +
      '<div style="min-width:0"><div class="file-row__name" title="' + M.esc(it.file.name) + '">' + M.esc(r ? r.name : it.file.name) + "</div>" +
      '<div class="file-row__meta">' + meta + "</div></div>" +
      '<div class="file-row__actions">' +
      (it.status === "done" ? '<button class="btn btn--sm" type="button" data-act="dl" data-id="' + it.id + '">' + DL_ICON + "Tải</button>" : "") +
      '<button class="btn btn--sm btn--ghost icon-btn" style="width:34px;height:34px" type="button" data-act="rm" data-id="' + it.id + '" aria-label="Bỏ ảnh này">' + X_ICON + "</button></div>";
  }
  function renderRow(it) {
    var li = el.list.querySelector('[data-row="' + it.id + '"]');
    if (li) li.innerHTML = rowHtml(it);
  }
  function render() {
    el.list.innerHTML = items.map(function (it) { return '<li class="file-row" data-row="' + it.id + '">' + rowHtml(it) + "</li>"; }).join("");
    el.listHead.hidden = !items.length;
    el.listTitle.textContent = items.length + " ảnh";
    renderStats();
  }
  function renderStats() {
    var done = items.filter(function (it) { return it.status === "done"; });
    var busy = items.some(function (it) { return it.status === "pending" || it.status === "working"; });
    var ai = done.filter(function (it) { return it.result.found.ai || it.result.found.c2pa; }).length;
    var gps = done.filter(function (it) { return it.result.found.gps; }).length;
    el.stats.hidden = !done.length;
    el.stats.innerHTML = '<div><strong>' + done.length + '</strong><span>Ảnh đã xử lý</span></div>' +
      '<div><strong>' + ai + '</strong><span>Có nhãn AI</span></div>' +
      '<div><strong>' + gps + '</strong><span>Có vị trí GPS</span></div>';
    el.zip.disabled = busy || !done.length;
    el.zipText.textContent = busy ? "Đang xử lý…" : done.length > 1 ? "Tải tất cả " + done.length + " ảnh (.zip)" : "Tải ảnh";
  }

  function run() {
    if (running) return;
    running = true;
    (function next() {
      var it = items.filter(function (x) { return x.status === "pending"; })[0];
      if (!it) { running = false; renderStats(); return; }
      it.status = "working"; renderRow(it);
      processFile(it.file).then(function (r) { it.result = r; it.status = "done"; })
        .catch(function () { it.status = "error"; })
        .then(function () { renderRow(it); renderStats(); setTimeout(next, 0); });
    })();
  }

  function addFiles(files) {
    var room = MAX_FILES - items.length;
    if (files.length > room) M.toast("Tối đa " + MAX_FILES + " ảnh mỗi lần, đã bỏ bớt " + (files.length - room) + " ảnh");
    files.slice(0, Math.max(0, room)).forEach(function (f) {
      items.push({ id: ++uid, file: f, status: "pending", thumb: URL.createObjectURL(f) });
    });
    render(); run();
  }

  F.dropzone($("drop"), {
    accept: "image/*,.heic,.heif", multiple: true, paste: true,
    filter: function (f) { return /^image\//.test(f.type) || /\.(jpe?g|png|webp|gif|bmp|avif|heic|heif|tiff?)$/i.test(f.name); },
    title: "Kéo thả ảnh vào đây",
    hint: "Ảnh tạo từ ChatGPT, Gemini, Midjourney, Firefly… hoặc ảnh chụp điện thoại. JPG, PNG, WebP giữ nguyên 100% chất lượng.",
    rejectMessage: "Chỉ nhận file ảnh",
    onFiles: addFiles
  });

  el.list.addEventListener("click", function (e) {
    var b = e.target.closest("button[data-act]");
    if (!b) return;
    var id = Number(b.getAttribute("data-id"));
    var it = items.filter(function (x) { return x.id === id; })[0];
    if (!it) return;
    if (b.getAttribute("data-act") === "rm") {
      URL.revokeObjectURL(it.thumb);
      items = items.filter(function (x) { return x.id !== id; });
      render();
    } else F.download(it.result.blob, it.result.name);
  });
  el.clearAll.addEventListener("click", function () {
    items.forEach(function (it) { URL.revokeObjectURL(it.thumb); });
    items = []; render();
  });
  el.zip.addEventListener("click", function () {
    var done = items.filter(function (it) { return it.status === "done"; });
    if (!done.length) return;
    if (done.length === 1) return F.download(done[0].result.blob, done[0].result.name);
    el.zip.disabled = true; el.zipText.textContent = "Đang đóng gói…";
    F.zipFiles(done.map(function (it) { return { name: it.result.name, blob: it.result.blob }; }),
      "anh-da-xoa-thong-tin-" + new Date().toISOString().slice(0, 10) + ".zip")
      .catch(function () { M.toast("Không tạo được file .zip, hãy tải từng ảnh"); })
      .then(renderStats);
  });

  // Cho phép kiểm thử tự động
  M.meta = { processFile: processFile };
  render();
})();
